package com.creastrix.platform.productmedia;

import java.io.ByteArrayOutputStream;
import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.zip.CRC32;

/** Admission for a single still JPEG or PNG. Inspect container dimensions and orientation
 * before decoding pixels. Compressed PNG comments/profiles and unknown ancillary chunks
 * must never be expanded just to create a buyer-facing thumbnail. */
record PhotoContainer(String mediaType, int width, int height, int orientation, byte[] decodeBytes, int grayTransparentSample) {
    private static final byte[] PNG = {(byte)137, 80, 78, 71, 13, 10, 26, 10};
    // PNG Third Edition, Table 17: white, red, green and blue chromaticities for sRGB.
    private static final int[] SRGB_CHRM = {31270,32900,64000,33000,30000,60000,15000,6000};

    boolean hasPngGraySamples() {
        if (!mediaType.equals("image/png")) return false;
        // All admitted PNGs start with the complete signature and IHDR; byte 25 is its colour type.
        int type = u8(decodeBytes,25);
        return type == 0 || type == 4;
    }

    static PhotoContainer inspect(byte[] data) {
        if (data.length >= 2 && u8(data, 0) == 255 && u8(data, 1) == 216) return jpeg(data);
        if (data.length >= PNG.length && Arrays.equals(data, 0, PNG.length, PNG, 0, PNG.length)) return png(data);
        throw new ProductPhotoProcessor.InvalidPhotoException();
    }

    private static void require(boolean valid) {
        if (!valid) throw new ProductPhotoProcessor.InvalidPhotoException();
    }
    private static int u8(byte[] data, int at) { return Byte.toUnsignedInt(data[at]); }
    private static int u16(byte[] data, int at) { return (u8(data, at) << 8) | u8(data, at + 1); }
    private static int i32(byte[] data, int at) { return (u16(data, at) << 16) | u16(data, at + 2); }

    private static PhotoContainer png(byte[] data) {
        var pixels = new ByteArrayOutputStream();
        pixels.writeBytes(PNG);
        int width = 0, height = 0, orientation = 1, chunks = 0, grayTransparentSample = -1;
        boolean exif = false, idat = false, endedData = false, palette = false, transparent = false;
        boolean srgb = false, gamma = false, chromaticities = false;
        var crc = new CRC32();
        for (int at = 8; at <= data.length - 12;) {
            int length = i32(data, at), body = at + 8;
            require(length >= 0 && length <= data.length - at - 12 && ++chunks <= 32768);
            String name = new String(data, at + 4, 4, StandardCharsets.ISO_8859_1);
            crc.reset(); crc.update(data, at + 4, length + 4);
            require((int) crc.getValue() == i32(data, body + length));
            require(chunks != 1 || name.equals("IHDR"));
            boolean copy = true;
            switch (name) {
                case "IHDR" -> {
                    require(chunks == 1 && length == 13);
                    width = i32(data, body); height = i32(data, body + 4);
                }
                case "PLTE" -> { require(!idat && !palette && length >= 3 && length <= 768 && length % 3 == 0); palette = true; }
                case "tRNS" -> {
                    require(!idat && !transparent && length > 0 && length <= 256); transparent = true;
                    if (u8(data,25) == 0) {
                        // The key is in original sample units, not the ImageIO destination's bit
                        // depth. Preserve it separately instead of asking the JPEG pipeline to
                        // trust an alpha band generated by comparing expanded low-bit samples.
                        require(length == 2);
                        int bits = u8(data,24);
                        require(bits == 1 || bits == 2 || bits == 4 || bits == 8 || bits == 16);
                        grayTransparentSample = u16(data,body);
                        require(grayTransparentSample < (1 << bits)); copy = false;
                    }
                }
                case "IDAT" -> { require(!endedData); idat = true; }
                case "IEND" -> {
                    require(length == 0 && idat && body + 4 == data.length);
                    pixels.write(data, at, 12);
                    return new PhotoContainer("image/png", width, height, orientation, pixels.toByteArray(),grayTransparentSample);
                }
                case "eXIf" -> {
                    require(!exif && length <= 65535); exif = true;
                    orientation = exifOrientation(data, body, length); copy = false;
                }
                case "sRGB" -> {
                    require(!srgb && !palette && !idat && length == 1 && u8(data,body) <= 3);
                    srgb = true; copy = false;
                }
                case "gAMA" -> {
                    require(!gamma && !palette && !idat && length == 4 && i32(data,body) == 45455);
                    gamma = true; copy = false;
                }
                case "cHRM" -> {
                    require(!chromaticities && !palette && !idat && length == 32);
                    for (int i=0;i<SRGB_CHRM.length;i++) require(i32(data,body+i*4) == SRGB_CHRM[i]);
                    chromaticities = true; copy = false;
                }
                // Reject animation and unsupported tagged colour rather than silently publishing
                // the first frame or rendering a non-sRGB master with a different appearance.
                case "acTL", "fcTL", "fdAT", "iCCP", "cICP", "mDCV", "cLLI" -> throw new ProductPhotoProcessor.InvalidPhotoException();
                default -> { require((data[at + 4] & 32) != 0); copy = false; }
            }
            if (idat && !name.equals("IDAT")) endedData = true;
            if (copy) pixels.write(data, at, length + 12);
            at += length + 12;
        }
        throw new ProductPhotoProcessor.InvalidPhotoException();
    }

    private static PhotoContainer jpeg(byte[] data) {
        int at = 2, width = 0, height = 0, orientation = 1, segments = 0, scans = 0, channels = 0;
        int iccParts = 0, iccCount = 0, iccBytes = 0;
        boolean entropy = false, exif = false;
        while (at < data.length) {
            if (entropy) while (at < data.length && u8(data, at) != 255) at++;
            require(at < data.length && u8(data, at) == 255);
            while (at < data.length && u8(data, at) == 255) at++;
            require(at < data.length);
            int marker = u8(data, at++);
            if (entropy && (marker == 0 || marker >= 0xd0 && marker <= 0xd7)) continue;
            entropy = false;
            if (marker == 0xd9) {
                require(at == data.length && scans > 0 && width > 0 && height > 0 && iccCount == iccParts);
                // The JPEG ImageIO colour conversion below is supported for RGB ICC input only.
                require(iccCount == 0 || channels == 3);
                return new PhotoContainer("image/jpeg", width, height, orientation, data,-1);
            }
            require(marker != 0 && marker != 1 && !(marker >= 0xd0 && marker <= 0xd8)
                    && at <= data.length - 2 && ++segments <= 32768);
            int length = u16(data, at), body = at + 2;
            require(length >= 2 && length <= data.length - at);
            if (marker >= 0xc0 && marker <= 0xcf && marker != 0xc4 && marker != 0xc8 && marker != 0xcc) {
                require(marker <= 0xc2 && width == 0 && height == 0 && length >= 11 && u8(data, body) == 8);
                height = u16(data, body + 1); width = u16(data, body + 3);
                channels = u8(data, body + 5);
                require((channels == 1 || channels == 3) && length == 8 + 3 * channels);
                require(width > 0 && height > 0);
            } else if (marker == 0xe1 && length >= 8 && header(data, body, "Exif\0\0")) {
                require(!exif); exif = true;
                orientation = exifOrientation(data, body + 6, length - 8);
            } else if (marker == 0xe2 && length >= 6 && header(data, body, "MPF\0")) {
                throw new ProductPhotoProcessor.InvalidPhotoException();
            } else if (marker == 0xe2 && length >= 14 && header(data, body, "ICC_PROFILE\0")) {
                // Preserve the profile for the colour-managed JPEG reader; incomplete, late or
                // conflicting chunks are not evidence of untagged sRGB.
                require(scans == 0 && length > 16);
                if (iccCount == 0) iccParts = u8(data,body+13);
                require(u8(data,body+12) == ++iccCount && u8(data,body+13) == iccParts && iccCount <= iccParts);
                iccBytes += length-16;
                require(iccBytes <= 1024*1024);
            } else if (marker == 0xda) {
                require(width > 0 && ++scans <= 64); entropy = true;
            }
            at += length;
        }
        throw new ProductPhotoProcessor.InvalidPhotoException();
    }

    private static boolean header(byte[] data, int at, String header) {
        for (int i = 0; i < header.length(); i++) if (u8(data, at + i) != header.charAt(i)) return false;
        return true;
    }

    /** IFD0 supplies orientation; only IFD0 and the Exif photo directory are inspected for
     * colour declarations. Never follow private GPS, thumbnail or maker-note pointers. */
    private static int exifOrientation(byte[] data, int start, int length) {
        require(length >= 8);
        var tiff = ByteBuffer.wrap(data, start, length).slice();
        int endian = Short.toUnsignedInt(tiff.getShort(0));
        require(endian == 0x4949 || endian == 0x4d4d);
        tiff.order(endian == 0x4949 ? ByteOrder.LITTLE_ENDIAN : ByteOrder.BIG_ENDIAN);
        require(tiff.getShort(2) == 42);
        int offset = tiff.getInt(4);
        int exifOffset = 0;
        int count = ifdSize(tiff,offset);
        int orientation = 1; boolean found = false;
        for (int n = 0; n < count; n++) {
            int entry = offset + 2 + n * 12, tag = Short.toUnsignedInt(tiff.getShort(entry));
            requireSupportedExifColour(tiff,entry,tag);
            if (tag == 0x8769) {
                require(exifOffset == 0 && tiff.getShort(entry + 2) == 4 && tiff.getInt(entry + 4) == 1);
                exifOffset = tiff.getInt(entry + 8); require(exifOffset >= 8 && exifOffset != offset);
            }
            if (tag != 0x0112) continue;
            require(!found && tiff.getShort(entry + 2) == 3 && tiff.getInt(entry + 4) == 1);
            found = true; orientation = Short.toUnsignedInt(tiff.getShort(entry + 8));
            require(orientation >= 1 && orientation <= 8);
        }
        if (exifOffset != 0) {
            int entries = ifdSize(tiff,exifOffset);
            for (int n=0;n<entries;n++) {
                int entry=exifOffset+2+n*12;
                requireSupportedExifColour(tiff,entry,Short.toUnsignedInt(tiff.getShort(entry)));
            }
        }
        return orientation;
    }
    private static int ifdSize(ByteBuffer tiff, int offset) {
        int length = tiff.limit();
        require(offset >= 8 && offset <= length - 2);
        int count = Short.toUnsignedInt(tiff.getShort(offset));
        require(offset + 2L + 12L * count + 4 <= length);
        return count;
    }
    private static void requireSupportedExifColour(ByteBuffer tiff, int entry, int tag) {
        if (tag == 0xa001) require(tiff.getShort(entry+2) == 3 && tiff.getInt(entry+4) == 1
                && Short.toUnsignedInt(tiff.getShort(entry+8)) == 1); // Exif ColorSpace = sRGB.
        // Uninterpreted TIFF transfer functions, primaries, ICC and gamma must not be ignored.
        require(tag != 0x012d && tag != 0x013e && tag != 0x013f && tag != 0x8773 && tag != 0xa500);
    }
}
